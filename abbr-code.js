// ===================================================================
// 品項簡寫 → 代號(品項簡寫分頁用,使用者 2026-10-28)。
// 不另外寫一套比對規則:先照出貨單的規則算出中文簡寫,再把裡面的顏色、款式換成字母,
// 所以中文那邊改了規則,代號會自動跟著變。使用者定的代號規則:
//   顏色:黃 Y、粉 P、綠 G、白 W、黑 B;灰 照寫中文
//   款式:招財/金運 $、招福 F
//   胖胖貓 不寫品名;大中小巨不加括號;其他品名、其他字 照寫中文
// 例:胖胖貓(大)黃金 → 大Y$、瘦貓8cm灰福 → 瘦貓8cm灰F
// ===================================================================

const ABBR_CODE_MAP = { 黃: "Y", 粉: "P", 綠: "G", 白: "W", 黑: "B", 金: "$", 福: "F" };

// 這些詞裡面剛好有「金」「福」「黃」「白」這些字,但不是顏色/款式,要整個跳過不換
// (金牛座、福氣牛、白沙屯…)。由長到短比對,新品名撞字的話加在這裡
const ABBR_CODE_KEEP = [
  "金牛座", "金牛", "福氣牛", "白沙屯", "黃金葛", "金錢", "金幣",
].sort((a, b) => b.length - a.length);

// 中文簡寫(compact,例如「胖胖貓(大)黃金 x2」)→「胖胖貓(大)Y$ x2」
function buildAbbrCode(compact) {
  // 胖胖貓是主力商品,代號不寫品名(只有胖胖貓這樣);大中小巨一律不加括號(使用者 2026-10-28)
  // 胖胖貓(大)黃金 → 大Y$、雙手貓(中)黃 → 雙手貓中Y
  // 【大小貓組】裡面裝的也是胖胖貓,一樣不寫:【大小貓組】大黃金+小黃+木片 → 大Y$+小Y+木片
  const s = String(compact ?? "").replace(/胖胖貓|【大小貓組】/g, "")
    .replace(/[(（]\s*(大|中|小|巨)(一對)?\s*[)）]/g, "$1$2");
  let out = "", i = 0;
  while (i < s.length) {
    const keep = ABBR_CODE_KEEP.find(k => s.startsWith(k, i));
    if (keep) { out += keep; i += keep.length; continue; }
    out += ABBR_CODE_MAP[s[i]] ?? s[i];
    i++;
  }
  return out;
}

if (typeof module !== "undefined" && module.exports) {
  module.exports = { buildAbbrCode, ABBR_CODE_MAP };
}
